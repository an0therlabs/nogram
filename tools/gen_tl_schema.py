#!/usr/bin/env python3
"""Generates Sources/mtproto/ngtl_schema.c from the repo's swift_scheme.tl:
every constructor of the types section as {id, name, "field:type ..."},
sorted by id for a binary search. The decoder (ngtl.c) reads any object
with it, so new optional fields in a layer never derail parsing.
Usage: tools/gen_tl_schema.py [path/to/swift_scheme.tl]"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "..", "submodules", "TelegramApi", "swift_scheme.tl")
out = os.path.join(here, "..", "Sources", "mtproto", "ngtl_schema.c")

entries = []
for line in open(src, encoding="utf-8"):
    line = line.strip()
    if line.startswith("---functions---"):
        break
    m = re.match(r"^([a-zA-Z0-9_.]+)#([0-9a-f]+)\s*(.*?)\s*=\s*([^;]+);$", line)
    if not m:
        continue
    name, cid, fields, _ = m.groups()
    if name in ("vector",):
        continue
    parts = [f for f in fields.split() if ":" in f and not f.startswith("{")]
    entries.append((int(cid, 16), name, " ".join(parts)))

entries.sort()
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/gen_tl_schema.py from swift_scheme.tl. Do not edit. */\n")
    f.write('#include "ngtl.h"\n\n')
    f.write("const ngtl_constructor ngtl_constructors[] = {\n")
    for cid, name, fields in entries:
        f.write('    { 0x%08xu, "%s", "%s" },\n' % (cid, name, fields))
    f.write("};\n")
    f.write("const int ngtl_constructor_count = %d;\n" % len(entries))
print("%d constructors -> %s" % (len(entries), out))
